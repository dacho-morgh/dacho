const PROVINCES_BY_NAME = new Map(IRAN_PROVINCES.map((province) => [province.name, province]))

export function citiesOfProvince(province: string): readonly string[] {
  return PROVINCES_BY_NAME.get(province)?.cities ?? []
}

export function isKnownProvince(province: string): boolean {
  return PROVINCES_BY_NAME.has(province)
}

export function isCityOfProvince(province: string, city: string): boolean {
  return citiesOfProvince(province).includes(city)
}
